import 'reflect-metadata';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createHash, randomUUID } from 'node:crypto';
import jwt from 'jsonwebtoken';
import { IdentityPasswords } from '../src/auth/passwords';
import { Tokens, ROLE_CLAIM, NAME_CLAIM } from '../src/auth/tokens';
import { normalizeRole, permissions } from '../src/identity/roles';
import { validRole, validText, validUsername } from '../src/users/users.service';
import { ProblemFilter } from '../src/common/problem.filter';
import { ArgumentsHost } from '@nestjs/common';

const fixture=JSON.parse(readFileSync('test/fixtures/generated.json','utf8'));
process.env.JWT_KEY='fixture-only-signing-key-at-least-32-characters';
process.env.JWT_ISSUER='test';process.env.JWT_AUDIENCE='test';
const passwords=new IdentityPasswords();
for(const item of fixture.hashes as {format:string;hash:string}[]) {
  test(`${item.format} generated by .NET accepts existing password`,async()=>assert.equal(await passwords.verify(item.hash,fixture.password),true));
  test(`${item.format} rejects wrong password`,async()=>assert.equal(await passwords.verify(item.hash,'wrong'),false));
}
for(const value of ['', 'not-base64', 'AAAA', Buffer.alloc(90,255).toString('base64')])
  test(`rejects malformed hash (${value.length} chars)`,async()=>assert.equal(await passwords.verify(value,'value'),false));
test('Node creates compatible IdentityV3 headers and salted hashes',async()=>{
  const one=await passwords.hash(fixture.password),two=await passwords.hash(fixture.password);
  assert.ok(one!==two,'Hashes must use independent salts');assert.equal(Buffer.from(one,'base64').readUInt32BE(1),2);
  assert.equal(Buffer.from(one,'base64').readUInt32BE(5),100000);assert.equal(await passwords.verify(one,fixture.password),true);
});
test('rejects a malformed embedded PRF and excessive iterations',async()=>{
  const bytes=Buffer.from(fixture.hashes[0].hash,'base64');bytes.writeUInt32BE(0xffffffff,5);
  assert.equal(await passwords.verify(bytes.toString('base64'),fixture.password),false);
  bytes.writeUInt32BE(100000,5);bytes.writeUInt32BE(20,1);
  assert.equal(await passwords.verify(bytes.toString('base64'),fixture.password),false);
});
test('verifies a real .NET JWT',()=>assert.equal(new Tokens().verify(fixture.token).sub,fixture.userId));
test('issued token preserves issuer, audience, lifetime and URI claims',()=>{
  const tokens=new Tokens(),id=randomUUID();
  const session=tokens.issue({id,name:'Admin',username:'admin',role:'Administrator'});
  const claims=tokens.verify(session.accessToken);
  assert.equal(claims.sub,id);assert.equal(claims.iss,'test');assert.equal(claims.aud,'test');
  assert.equal(claims[NAME_CLAIM],'Admin');assert.equal(claims[ROLE_CLAIM],'Administrator');
  assert.equal(claims.exp!-claims.iat!,3600);
});
for(const defect of ['signature','issuer','audience','expiration','altered','missing-exp']) {
  test(`rejects JWT ${defect}`,()=>{
    const key=createHash('sha256').update(defect==='signature'?'wrong':process.env.JWT_KEY!).digest();
    const payload:Record<string,unknown>={sub:randomUUID(),exp:Math.floor(Date.now()/1000)+(defect==='expiration'?-10:100)};
    if(defect==='missing-exp') delete payload.exp;
    let token=jwt.sign(payload,key,{algorithm:'HS256',issuer:defect==='issuer'?'wrong':'test',audience:defect==='audience'?'wrong':'test'});
    if(defect==='altered') token=token.slice(0,-10)+'AAAAAAAAAA';
    assert.throws(()=>new Tokens().verify(token));
  });
}
for(const role of ['Administrator','Operator','ConsultationUser','User'])
  test(`normalizes role ${role}`,()=>assert.equal(normalizeRole(role),role==='User'?'ConsultationUser':role));
test('only administrators receive user-management permission',()=>{
  assert.ok(permissions('Administrator').includes('AdministratorOnly'));
  assert.ok(!permissions('Operator').includes('AdministratorOnly'));
  assert.ok(permissions('Operator').includes('OperateSystem'));
  assert.ok(!permissions('ConsultationUser').includes('OperateSystem'));
});
test('validates usernames and official roles',()=>{
  assert.equal(validUsername(' ADMIN@EXAMPLE.TEST '),'admin@example.test');
  for(const value of ['', 'a b','a\u0000b','a'.repeat(255)]) assert.throws(()=>validUsername(value));
  for(const value of ['User','SuperAdmin',null]) assert.throws(()=>validRole(value));
  assert.throws(()=>validText('',150,'required'));assert.throws(()=>validText('a'.repeat(151),150,'required'));
});
for(const [error,status] of [[new Error('private database connection information'),500],[{code:'23505'},409],[{code:'ECONNREFUSED'},503]] as const) {
  test(`sanitizes internal failures as HTTP ${status}`,()=>{
    const output:{status?:number;body?:unknown}={};
    const response={status:(value:number)=>{output.status=value;return response;},type:(_value:string)=>response,json:(body:unknown)=>{output.body=body;return response;}};
    const host={switchToHttp:()=>({getResponse:()=>response,getRequest:()=>({headers:{}})})} as unknown as ArgumentsHost;
    new ProblemFilter().catch(error,host);
    assert.equal(output.status,status);assert.ok(!JSON.stringify(output.body).includes('private database'));
    assert.ok(!JSON.stringify(output.body).includes('stack'));
  });
}
